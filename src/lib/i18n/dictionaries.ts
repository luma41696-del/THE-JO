const DICTIONARIES: Record<Locale, Dictionary> = { en, ar };

/**
 * Look up the dictionary for a locale.
 *
 * Synchronous and fully bundled: the whole thing is a few kilobytes, and
 * splitting it per-locale would add a network round trip to the critical path
 * to save less than a typical product image.
 */
export function getDictionary(locale: Locale): Dictionary {
  return DICTIONARIES[locale] ?? en;
}

