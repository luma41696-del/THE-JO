/**
 * net sale — brand asset generator.
 *
 *   node scripts/generate-brand.mjs
 *
 * Single source of truth for every piece of brand geometry on the site. Reads
 * `scripts/brand-paths.json` (cubic bezier outlines traced from the master logo
 * artwork, normalised to a 120x120 box) and emits:
 *
 *   public/brand/net-sale-mark.svg        light-ground mark
 *   public/brand/net-sale-mark-light.svg  dark-ground mark
 *   public/brand/net-sale-mark-ink.svg    single-colour, for print and favicons
 *   public/brand/net-sale-icon.svg        padded square favicon
 *   public/lottie/net-sale-wave.json      morphing pebble + ripple rings
 *   src/components/brand/paths.ts         typed path constants for React/Motion
 *
 * The monogram is **knocked out** of the pebble in the artwork — the N is a
 * hole, not a drawn shape — so it is rendered in the ground colour on top of
 * the blob rather than as a separate coloured mark. That is what lets the same
 * geometry sit on cream, on ink, or on red without re-cutting the artwork.
 *
 * Re-run this after re-tracing. Never hand-edit the outputs: the wave variants
 * must keep an identical command sequence to the base blob or Motion can no
 * longer interpolate between them.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");

const B = JSON.parse(readFileSync(join(__dirname, "brand-paths.json"), "utf8"));

/** Sampled from the supplied palette swatch. */
const RED = "#CE1212";
const RED_DEEP = "#810000";
const INK = "#1B1717";
const CREAM = "#EEEBDD";

/* ========================================================================== */
/*  SVG                                                                       */
/* ========================================================================== */

const monoPaths = (fill) =>
  B.monogram.map((d) => `  <path d="${d}" fill="${fill}"/>`).join("\n");

const mark = (blob, mono, dot) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${B.viewBox}" fill="none" role="img" aria-label="net sale">
  <path d="${B.blob}" fill="${blob}"/>
  <path d="${B.dot}" fill="${dot}"/>
${monoPaths(mono)}
</svg>
`;

function writeSvgs() {
  const dir = join(ROOT, "public", "brand");
  mkdirSync(dir, { recursive: true });

  // On cream: red pebble, cream N knocked out of it.
  writeFileSync(join(dir, "net-sale-mark.svg"), mark(RED, CREAM, RED));
  // On ink: identical, with the N cut to the dark ground.
  writeFileSync(join(dir, "net-sale-mark-light.svg"), mark(RED, INK, RED));
  // Single colour, for embroidery, stamps and anywhere red is unavailable.
  writeFileSync(join(dir, "net-sale-mark-ink.svg"), mark(INK, CREAM, INK));

  writeFileSync(
    join(dir, "net-sale-icon.svg"),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-6 -6 132 132" fill="none">
  <rect x="-6" y="-6" width="132" height="132" rx="30" fill="${INK}"/>
  <path d="${B.blob}" fill="${RED}"/>
  <path d="${B.dot}" fill="${RED}"/>
${B.monogram.map((d) => `  <path d="${d}" fill="${INK}"/>`).join("\n")}
</svg>
`,
  );

  return 4;
}

